// 当前语言（null = 跟随系统，由 core.js 解析后写入）
let lang = 'zh';

function t(key, vars) {
  const dict = I18N[lang] || I18N.zh;
  let s = dict[key] != null ? dict[key] : (I18N.zh[key] != null ? I18N.zh[key] : key);
  if (vars) {
    for (const k of Object.keys(vars)) {
      s = s.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return s;
}
